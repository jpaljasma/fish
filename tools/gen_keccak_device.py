#!/usr/bin/env python3
"""Generate third_party/keccak_device.cuh from third_party/keccak.c.

Extracts rol, round_constants, and keccakf1600 verbatim and adds CUDA
__device__ annotations, so the device permutation is byte-exactly the
CPU reference's. Regenerate when third_party/keccak.c changes.
"""
import re
import sys
from pathlib import Path

root = Path(__file__).resolve().parent.parent
src = (root / "third_party" / "keccak.c").read_text()
out_path = root / "third_party" / "keccak_device.cuh"


def extract_fn(text, name):
    """Extract a top-level function by brace matching (any return type)."""
    m = re.search(rf"^[ \t]*(?:static\s+)?[\w\s\*]+?\b{name}\s*\(", text, re.M)
    if not m:
        sys.exit(f"function {name} not found")
    start = m.start()
    i = text.index("{", m.end())
    depth = 0
    for j in range(i, len(text)):
        if text[j] == "{":
            depth += 1
        elif text[j] == "}":
            depth -= 1
            if depth == 0:
                return text[start : j + 1]
    sys.exit(f"unbalanced braces in {name}")


rol_fn = extract_fn(src, "rol").replace("static uint64_t rol", "uint64_t rol")
keccakf = extract_fn(src, "keccakf1600")
rc = re.search(r"static const uint64_t round_constants\[24\]\s*=\s*\{.*?\};", src, re.S)
if not rc:
    sys.exit("round_constants not found")
round_constants = rc.group(0).replace(
    "static const uint64_t round_constants[24]",
    "static __device__ const uint64_t round_constants[24]")

out = f"""// Auto-generated by tools/gen_keccak_device.py from third_party/keccak.c
// (functions rol, round_constants, keccakf1600, verbatim bodies).
// CUDA device port for FishHash dataset construction. Do not edit by hand;
// regenerate: python tools/gen_keccak_device.py
#pragma once
#include <stdint.h>

__device__ __forceinline__ {rol_fn}

{round_constants}

__device__ __forceinline__ {keccakf}
"""

out_path.write_text(out)
print(f"wrote {out_path} ({len(out)} bytes)")
